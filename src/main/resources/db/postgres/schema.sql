-- Travel Shopping & Reservation API schema (PostgreSQL). Timestamps are UTC wall-clock values.
CREATE TABLE IF NOT EXISTS airport (
    iata      CHAR(3) PRIMARY KEY,
    icao      CHAR(4) NOT NULL,
    name      TEXT NOT NULL,
    city      TEXT NOT NULL,
    country   CHAR(2) NOT NULL,
    timezone  TEXT NOT NULL,
    latitude  DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS airline (
    iata     CHAR(2) PRIMARY KEY,
    icao     CHAR(3) NOT NULL,
    name     TEXT NOT NULL,
    country  CHAR(2) NOT NULL,
    alliance TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS flight (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number    VARCHAR(7) NOT NULL,
    airline_iata     CHAR(2) NOT NULL REFERENCES airline (iata),
    origin_iata      CHAR(3) NOT NULL REFERENCES airport (iata),
    destination_iata CHAR(3) NOT NULL REFERENCES airport (iata),
    departure        TIMESTAMP NOT NULL,
    arrival          TIMESTAMP NOT NULL,
    aircraft         VARCHAR(8) NOT NULL,
    duration_minutes INT NOT NULL
);
CREATE INDEX IF NOT EXISTS flight_route_departure_idx ON flight (origin_iata, destination_iata, departure);

CREATE TABLE IF NOT EXISTS fare (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id           BIGINT NOT NULL REFERENCES flight (id),
    booking_class       CHAR(1) NOT NULL,
    cabin               VARCHAR(16) NOT NULL,
    base_amount         NUMERIC(10, 2) NOT NULL,
    currency            CHAR(3) NOT NULL,
    refundable          BOOLEAN NOT NULL,
    changeable          BOOLEAN NOT NULL,
    baggage_included_kg INT NOT NULL,
    seats_available     INT NOT NULL,
    UNIQUE (flight_id, booking_class)
);
CREATE INDEX IF NOT EXISTS fare_flight_idx ON fare (flight_id);

CREATE TABLE IF NOT EXISTS tax_rule (
    code            VARCHAR(16) PRIMARY KEY,
    kind            VARCHAR(20) NOT NULL,
    country         CHAR(2),
    airport_iata    CHAR(3),
    airline_iata    CHAR(2),
    min_distance_km INT,
    max_distance_km INT,
    amount          NUMERIC(10, 2) NOT NULL,
    currency        CHAR(3) NOT NULL
);

CREATE TABLE IF NOT EXISTS traveler (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name            TEXT NOT NULL,
    last_name             TEXT NOT NULL,
    date_of_birth         DATE NOT NULL,
    email                 TEXT NOT NULL,
    nationality           CHAR(2) NOT NULL,
    frequent_flyer_number VARCHAR(16)
);
CREATE INDEX IF NOT EXISTS traveler_last_name_idx ON traveler (last_name);

CREATE TABLE IF NOT EXISTS booking (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_locator CHAR(6) NOT NULL UNIQUE,
    status         VARCHAR(10) NOT NULL,
    created_at     TIMESTAMP NOT NULL,
    total_amount   NUMERIC(12, 2) NOT NULL,
    currency       CHAR(3) NOT NULL
);

CREATE TABLE IF NOT EXISTS booking_traveler (
    booking_id  BIGINT NOT NULL REFERENCES booking (id),
    traveler_id BIGINT NOT NULL REFERENCES traveler (id),
    PRIMARY KEY (booking_id, traveler_id)
);

CREATE TABLE IF NOT EXISTS booking_segment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    BIGINT NOT NULL REFERENCES booking (id),
    fare_id       BIGINT NOT NULL REFERENCES fare (id),
    booking_class CHAR(1) NOT NULL,
    cabin         VARCHAR(16) NOT NULL
);
CREATE INDEX IF NOT EXISTS booking_segment_booking_idx ON booking_segment (booking_id);
